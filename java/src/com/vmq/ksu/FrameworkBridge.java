package com.vmq.ksu;

import android.content.ComponentName;
import android.content.Context;
import android.service.notification.NotificationListenerService;

import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;

/** Accesses hidden notification-listener APIs without adding hidden framework types to javac. */
public final class FrameworkBridge {
    private static final ComponentName LISTENER_COMPONENT =
            new ComponentName("android", "com.vmq.ksu.Listener");

    private FrameworkBridge() {
    }

    /**
     * Avoids a SettingsProvider lookup while Android 15 unmarshals notifications for app_process.
     * The flag class is generated by the device framework, so older or differently generated ROMs
     * may not expose it and do not need this workaround.
     */
    public static boolean prepareNotificationParceling() throws Exception {
        try {
            Class<?> featureFlags = Class.forName("android.app.FeatureFlagsImpl");
            Field systemUiCached = featureFlags.getDeclaredField("systemui_is_cached");
            systemUiCached.setAccessible(true);
            systemUiCached.setBoolean(null, true);
            return systemUiCached.getBoolean(null);
        } catch (ClassNotFoundException exception) {
            return false;
        } catch (NoSuchFieldException exception) {
            return false;
        }
    }

    public static ComponentName register(
            NotificationListenerService listener, Context context, int userId) throws Exception {
        invoke(
                NotificationListenerService.class.getDeclaredMethod(
                        "registerAsSystemService", Context.class, ComponentName.class, int.class),
                listener,
                context,
                LISTENER_COMPONENT,
                userId);
        return LISTENER_COMPONENT;
    }

    public static void unregister(NotificationListenerService listener) throws Exception {
        invoke(
                NotificationListenerService.class.getDeclaredMethod("unregisterAsSystemService"),
                listener);
    }

    private static void invoke(Method method, Object receiver, Object... arguments) throws Exception {
        try {
            method.setAccessible(true);
            method.invoke(receiver, arguments);
        } catch (InvocationTargetException exception) {
            Throwable cause = exception.getCause();
            if (cause instanceof Exception) {
                throw (Exception) cause;
            }
            if (cause instanceof Error) {
                throw (Error) cause;
            }
            throw exception;
        }
    }
}
